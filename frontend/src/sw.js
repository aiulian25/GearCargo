// Handle push notifications
self.addEventListener('push', (event) => {
  if (!event.data) return

  // R4-28: a non-JSON push used to throw here and the notification was dropped
  // without a trace.
  const data = parsePushData(event.data)
  
  const options = {
    body: data.body || 'New notification',
    icon: '/icons/logo-192.png',
    badge: '/icons/logo-72.png',
    vibrate: [100, 50, 100],
    data: {
      url: notificationTarget(data, self.location.origin),
    },
    actions: data.actions || [],
    tag: data.tag || 'gearcargo-notification',
    renotify: true,
  }
  
  event.waitUntil(
    self.registration.showNotification(data.title || 'GearCargo', options)
  )
})

// Handle notification click
self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  
  const urlToOpen = notificationTarget(event.notification, self.location.origin)
  
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true })
      .then((clientList) => {
        // R4-28: compare paths, not an absolute URL against a path — the old
        // check never matched, so every click opened a duplicate tab.
        const existing = findClientToFocus(clientList, urlToOpen)
        if (existing) {
          return existing.focus()
        }
        if (self.clients.openWindow) {
          return self.clients.openWindow(urlToOpen)
        }
      })
  )
})

